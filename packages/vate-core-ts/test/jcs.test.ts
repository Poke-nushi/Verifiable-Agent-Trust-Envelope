import { describe, expect, it } from "vitest";
import {
  canonicalizeJcsJson,
  JCS_INPUT_LIMITS,
  JcsInputError,
  stableJsonString,
} from "../src/index.js";

const encode = (text: string) => new TextEncoder().encode(text);
const canonical = (text: string) => new TextDecoder().decode(canonicalizeJcsJson(encode(text)));

function rejects(source: string | Uint8Array, code: string): void {
  expect(() => canonicalizeJcsJson(typeof source === "string" ? encode(source) : source))
    .toThrow(expect.objectContaining({ name: "JcsInputError", code }));
}

describe("RFC 8785 bytes from original JSON", () => {
  it("matches the complete byte example in RFC 8785 sections 3.2.2–3.2.4", () => {
    const source = String.raw`{
      "numbers": [333333333.33333329, 1E30, 4.50, 2e-3, 0.000000000000000000000000001],
      "string": "\u20ac$\u000F\u000aA'\u0042\u0022\u005c\\\"\/",
      "literals": [null, true, false]
    }`;
    // RFC 8785 section 3.2.4, not generated by this implementation.
    const expectedHex = "7b226c69746572616c73223a5b6e756c6c2c747275652c66616c73655d2c226e756d62657273223a" +
      "5b3333333333333333332e333333333333332c31652b33302c342e352c302e3030322c31652d3237" +
      "5d2c22737472696e67223a22e282ac245c75303030665c6e4127425c225c5c5c5c5c222f227d";
    const hex = Array.from(canonicalizeJcsJson(encode(source)), (byte) => byte.toString(16).padStart(2, "0")).join("");
    expect(hex).toBe(expectedHex);
  });

  it("sorts unescaped UTF-16 names as in RFC 8785 section 3.2.3", () => {
    const source = String.raw`{"\u20ac":"euro","\r":"return","\ufb33":"hebrew","1":"one","\ud83d\ude00":"emoji","\u0080":"control","\u00f6":"latin"}`;
    expect(canonical(source)).toBe('{"\\r":"return","1":"one","\u0080":"control","ö":"latin","€":"euro","😀":"emoji","דּ":"hebrew"}');
    const differentOrder = String.raw`{"\ue000":2,"\ud800\udc00":1}`;
    expect(canonical(differentOrder)).toBe('{"𐀀":1,"\ue000":2}');
    expect(stableJsonString(JSON.parse(differentOrder))).toBe('{"\\ue000":2,"\\ud800\\udc00":1}');
  });

  it.each([
    ["0000000000000000", "0"], ["8000000000000000", "0"],
    ["0000000000000001", "5e-324"], ["8000000000000001", "-5e-324"],
    ["7fefffffffffffff", "1.7976931348623157e+308"], ["ffefffffffffffff", "-1.7976931348623157e+308"],
    ["4340000000000000", "9007199254740992"], ["c340000000000000", "-9007199254740992"],
    ["4430000000000000", "295147905179352830000"],
    ["44b52d02c7e14af5", "9.999999999999997e+22"], ["44b52d02c7e14af6", "1e+23"],
    ["44b52d02c7e14af7", "1.0000000000000001e+23"], ["444b1ae4d6e2ef4e", "999999999999999700000"],
    ["444b1ae4d6e2ef4f", "999999999999999900000"], ["444b1ae4d6e2ef50", "1e+21"],
    ["3eb0c6f7a0b5ed8c", "9.999999999999997e-7"], ["3eb0c6f7a0b5ed8d", "0.000001"],
    ["41b3de4355555553", "333333333.3333332"], ["41b3de4355555554", "333333333.33333325"],
    ["41b3de4355555555", "333333333.3333333"], ["41b3de4355555556", "333333333.3333334"],
    ["41b3de4355555557", "333333333.33333343"], ["becbf647612f3696", "-0.0000033333333333333333"],
    ["43143ff3c1cb0959", "1424953923781206.2"],
  ])("matches RFC 8785 Appendix B binary64 %s", (bits, expected) => {
    const view = new DataView(new ArrayBuffer(8));
    view.setBigUint64(0, BigInt(`0x${bits}`));
    const value = view.getFloat64(0);
    const source = Object.is(value, -0) ? "-0" : value.toString();
    expect(canonical(source)).toBe(expected);
  });

  it.each([
    ["1.0", "1"], ["1e0", "1"], ["-0.00", "0"], ["4.50", "4.5"],
    ["1424953923781206.25", "1424953923781206.2"],
    ["9007199254740993", "9007199254740992"], ["1e-999", "0"],
  ])("uses ECMAScript number conversion for %s", (source, expected) => {
    expect(canonical(source)).toBe(expected);
  });

  it("preserves Unicode sequences, nulls, array order and ordinary special keys", () => {
    expect(canonical('{"é":null,"é":false,"a":[3,2,1]}')).toBe('{"a":[3,2,1],"é":false,"é":null}');
    expect(canonical('{"2":2,"10":10,"__proto__":{"z":0,"a":1},"toJSON":null}'))
      .toBe('{"10":10,"2":2,"__proto__":{"a":1,"z":0},"toJSON":null}');
    expect(canonical('[{"z":2,"a":1},{"b":null,"a":false}]'))
      .toBe('[{"a":1,"z":2},{"a":false,"b":null}]');
    expect(canonical('"é😀\u007f"')).toBe('"é😀\u007f"');
    expect(canonical('"�"')).toBe('"�"');
  });

  it.each(["{}", "[]", "null", "true", "false", '""', '"\\b\\t\\n\\f\\r\\u0000"'])
    ("retains valid JSON primitives and empty containers: %s", (source) => {
      expect(canonical(` \t\r\n${source}\n`)).toBe(source);
    });

  it.each([
    '{"a":1,"a":2}', '{"a":1,"\\u0061":2}', '{"x":{"a":1,"a":2}}',
    '[{"a":1,"a":2}]', '{"/":1,"\\/":2}', '{"😀":1,"\\ud83d\\ude00":2}',
    '{"__proto__":1,"__proto__":2}', '{"":1,"":2}',
  ])("rejects duplicate names before serialization: %s", (source) => rejects(source, "duplicate_key"));

  it.each(['"\\ud800"', '"\\udfff"', '"\\ud800x"', '"\\ud800\\ud800"', '{"\\udfff":1}', '["\\udc00"]'])
    ("rejects isolated surrogates: %s", (source) => rejects(source, "invalid_unicode"));

  it.each([
    ...Array.from({ length: 32 }, (_, i) => 0xfdd0 + i),
    ...Array.from({ length: 17 }, (_, plane) => [plane * 0x10000 + 0xfffe, plane * 0x10000 + 0xffff]).flat(),
  ])("rejects I-JSON noncharacter %i in literal and escaped names and values", (point) => {
    const character = String.fromCodePoint(point);
    const escaped = character.split("").map(unit => "\\u" + unit.charCodeAt(0).toString(16).padStart(4, "0")).join("");
    for (const text of [character, escaped]) {
      rejects('{"note":"' + text + '"}', "invalid_unicode");
      rejects('{"' + text + '":0}', "invalid_unicode");
    }
  });

  it.each([
    0xfdcf, 0xfdf0,
    ...Array.from({ length: 17 }, (_, plane) => plane * 0x10000 + 0xfffd),
  ])("preserves permitted Unicode code point %i beside noncharacters", (point) => {
    const character = String.fromCodePoint(point);
    const source = JSON.stringify({ [character]: character });
    expect(canonical(source)).toBe(source);
  });

  it.each(["1e400", "-1e400", "[1e400]", '{"n":1e400}'])
    ("rejects non-finite conversion: %s", (source) => rejects(source, "non_finite_number"));

  it.each([
    "", " ", "NaN", "Infinity", "-Infinity", "+1", "01", "--1", "1.", "1e", ".1", "0x10",
    "[1,]", "[,1]", "[1 2]", "{a:1}", '{"a":}', '{"a":1,}', '{"a" 1}', '{"a":1 "b":2}',
    '"\\x20"', '"\\u00xz"', '"line\nfeed"', '"unclosed', '"trailing\\',
    "null true", "[truefalse]", "{}{}", "/* x */null", "\ufeffnull", "\u00a0null", "null\u0000",
  ])("rejects malformed source JSON: %s", (source) => rejects(source, "invalid_json"));

  it.each([[0xc0, 0xaf], [0xed, 0xa0, 0x80], [0xe2, 0x82], [0xff], [0xf4, 0x90, 0x80, 0x80]])
    ("rejects invalid UTF-8 without replacement: %s", (...bytes) => rejects(new Uint8Array(bytes), "invalid_utf8"));

  it("enforces byte and container-depth limits", () => {
    const exact = '"' + "a".repeat(JCS_INPUT_LIMITS.maxBytes - 2) + '"';
    expect(canonical(exact)).toBe(exact);
    rejects(exact + " ", "input_too_large");
    const multibyte = '"' + "é".repeat(JCS_INPUT_LIMITS.maxBytes / 2) + '"';
    rejects(multibyte, "input_too_large");
    const depth = JCS_INPUT_LIMITS.maxDepth;
    expect(canonical("[".repeat(depth) + "0" + "]".repeat(depth))).toBe("[".repeat(depth) + "0" + "]".repeat(depth));
    rejects("[".repeat(depth + 1) + "0" + "]".repeat(depth + 1), "nesting_too_deep");
    rejects('{"a":'.repeat(depth + 1) + "0" + "}".repeat(depth + 1), "nesting_too_deep");
  });

  it("requires original bytes and does not alter them", () => {
    expect(() => canonicalizeJcsJson({ a: 1 } as never)).toThrow(JcsInputError);
    const source = encode(' {"b":2,"a":1} ');
    const before = source.slice();
    canonicalizeJcsJson(source);
    expect(source).toEqual(before);
  });
});
